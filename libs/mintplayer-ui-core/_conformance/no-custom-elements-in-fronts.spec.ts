describe('no custom elements in framework fronts (#437 §9.1)', () => {
  const found = offenders();

  it('adds no new front that renders an <mp-*> element', () => {
    expect(found.filter((pair) => !NOT_YET_MIGRATED.includes(pair))).toEqual([]);
  });

  it('keeps the not-yet-migrated list current', () => {
    expect(NOT_YET_MIGRATED.filter((pair) => !found.includes(pair))).toEqual([]);
  });
});
