import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * PRD #437 §9.1: a framework front renders its own template and never an
 * `<mp-*>` (or `<mint-*>`) custom element. Under Angular SSR (domino, no
 * `customElements`) such an element is an empty box, and React/Vue SSR emit
 * it with no content either, which is the whole reason for the programme.
 *
 * A ratchet while the catalog migrates: {@link NOT_YET_MIGRATED} lists the
 * `<lib>:<entry>` pairs that still render an element. A new offender fails;
 * so does a listed pair that no longer renders one (delete its line when a
 * wave lands it). At M7 the list is empty and stays empty.
 */
const WORKSPACE = existsSync(join(process.cwd(), 'libs')) ? process.cwd() : join(process.cwd(), '..', '..');

const LIBS = { ng: 'mintplayer-ng-bootstrap', react: 'mintplayer-react-bootstrap', vue: 'mintplayer-vue-bootstrap' } as const;

const ELEMENT_USE: readonly RegExp[] = [
  /<(?:mp|mint)-[a-z]/, // template markup
  /tagName:\s*['"](?:mp|mint)-[a-z]/, // @lit/react createComponent
  /createElement\(\s*['"](?:mp|mint)-[a-z]/, // imperative
];

const isSource = (name: string): boolean =>
  /\.(ts|tsx|html|vue)$/.test(name) && !/\.spec\.|\.d\.ts$/.test(name);

const walk = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.name !== 'node_modules' && !entry.name.startsWith('.') && entry.name !== '_conformance')
    .flatMap((entry) => {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) return walk(full);
      return isSource(entry.name) ? [full] : [];
    });

function offenders(): string[] {
  const pairs = Object.entries(LIBS).flatMap(([key, lib]) => {
    const root = join(WORKSPACE, 'libs', lib);
    return walk(root)
      .filter((file) => ELEMENT_USE.some((pattern) => pattern.test(readFileSync(file, 'utf8'))))
      .map((file) => `${key}:${file.slice(root.length + 1).replace(/\\/g, '/').split('/')[0]}`);
  });
  return [...new Set(pairs)].sort();
}

