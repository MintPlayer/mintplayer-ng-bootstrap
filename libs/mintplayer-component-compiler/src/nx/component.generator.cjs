// `nx g mintplayer-component-compiler:component <name>` — scaffold a new
// component group (PRD #437 D10): the core entry (manifest, core, template,
// scoped sheet) and, in every front lib the config names, the entry point that
// re-exports the generated components. Run the `compile-components` target
// afterwards to generate them.
const { dirname, join } = require('node:path');
const { pathToFileURL } = require('node:url');
const { formatFiles, names } = require('@nx/devkit');

const exportSrc = "export * from './src';\n";

/** @param {import('@nx/devkit').Tree} tree */
async function componentGenerator(tree, schema) {
  const n = names(schema.name);
  const entry = n.fileName;
  const configFile = schema.config ?? 'libs/mintplayer-ui-core/component-compiler.config.mjs';
  const { default: config } = await import(`${pathToFileURL(join(tree.root, configFile)).href}?t=${Date.now()}`);
  const core = join(config.root, entry);
  if (tree.exists(join(core, 'index.ts'))) throw new Error(`${core} already exists`);

  const scope = `${n.constantName}_SCOPE`;
  const sheet = `${n.propertyName}ScopedStyles`;
  tree.write(join(core, 'index.ts'), exportSrc);
  tree.write(
    join(core, 'src', 'index.ts'),
    [
      `export { ${scope}, ${n.propertyName}Core } from './${entry}.core';`,
      `export type { ${n.className}Inputs, ${n.className}Props } from './${entry}.core';`,
      `// Generated by the \`codegen\` target from styles/${entry}.scoped.scss (gitignored).`,
      `export { ${sheet} } from './styles/${entry}.scoped.styles';`,
      '',
    ].join('\n'),
  );
  tree.write(
    join(core, 'src', `${entry}.core.ts`),
    [
      `import { defineCore, type CoreBag } from '${config.package}/component';`,
      '',
      `export const ${scope} = '${entry}';`,
      '',
      `export interface ${n.className}Inputs {`,
      `  disabled: boolean;`,
      `}`,
      '',
      `export interface ${n.className}Props {`,
      `  root: CoreBag;`,
      `}`,
      '',
      `export const ${n.propertyName}Core = defineCore<${n.className}Inputs, object, ${n.className}Props>({`,
      `  view: ({ inputs }) => ({`,
      `    root: { 'data-mps': ${scope}, class: '${entry}', 'aria-disabled': inputs.disabled ? 'true' : null },`,
      `  }),`,
      `});`,
      '',
    ].join('\n'),
  );
  tree.write(
    join(core, 'src', `${entry}.component.ts`),
    [
      `import type { ComponentGroup } from '${config.package}/component';`,
      '',
      `export default {`,
      `  group: '${entry}',`,
      `  styles: [{ scope: '${scope}', sheet: '${sheet}' }],`,
      `  components: {`,
      `    '${entry}': {`,
      `      core: '${n.propertyName}Core',`,
      `      doc: 'TODO: what ${entry} is.',`,
      `      inputs: { type: '${n.className}Inputs', fields: { disabled: { default: 'false', reflect: true } } },`,
      `    },`,
      `  },`,
      `} satisfies ComponentGroup;`,
      '',
    ].join('\n'),
  );
  tree.write(
    join(core, 'src', 'templates', `${entry}.view.vue`),
    [
      '<script setup lang="ts">',
      `import type { ${n.className}Props } from '${config.package}/${entry}';`,
      '',
      `defineProps<{ root: ${n.className}Props['root'] }>();`,
      'defineSlots<{ default?: () => unknown }>();',
      '</script>',
      '',
      '<template>',
      '  <div mp-host ref="root" v-bind="root"><slot /></div>',
      '</template>',
      '',
    ].join('\n'),
  );
  tree.write(join(core, 'src', 'styles', `${entry}.scoped.scss`), `.${entry} {\n  display: block;\n}\n`);

  // One entry point per front lib, re-exporting the generated components.
  Object.entries(config.fronts).forEach(([front, target]) => {
    const entryDir = dirname(dirname(target.outDir(entry)));
    tree.write(join(entryDir, 'index.ts'), exportSrc);
    tree.write(join(entryDir, 'src', 'index.ts'), `// Generated from ${config.package}/${entry} (PRD #437 D10).\nexport * from './generated';\n`);
    if (front === 'angular') {
      const sibling = tree
        .children(dirname(entryDir))
        .map((dir) => join(dirname(entryDir), dir, 'ng-package.json'))
        .find((file) => tree.exists(file));
      if (sibling) tree.write(join(entryDir, 'ng-package.json'), tree.read(sibling, 'utf-8'));
    }
  });

  if (!schema.skipFormat) await formatFiles(tree);
}

module.exports = componentGenerator;
module.exports.default = componentGenerator;
