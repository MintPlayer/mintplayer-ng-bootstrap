// Throwaway build step for spike S1. Deleted before merge.
//
// Compiles the REAL `_styles/form-select.styles.scss` with the same sass
// invocation the codegen uses, so the spike measures production CSS rather than
// a hand-written approximation, then bundles the Lit fixture with esbuild.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import * as sass from 'sass';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, '..', '..', '..');
const scss = join(repoRoot, 'libs/mintplayer-web-components/_styles/form-select.styles.scss');

const { css } = sass.compile(scss, {
  style: 'expanded',
  loadPaths: [dirname(scss), repoRoot, join(repoRoot, 'node_modules')],
  silenceDeprecations: ['import', 'global-builtin', 'color-functions', 'mixed-decls', 'slash-div', 'abs-percent', 'legacy-js-api'],
});

writeFileSync(
  join(here, 'generated-form-select.css.js'),
  `// AUTO-GENERATED by prepare.mjs from the real form-select.styles.scss\nexport const realFormSelectCss = ${JSON.stringify(css)};\n`,
);
console.log(`[prepare] compiled real form-select CSS: ${css.length} bytes`);

await esbuild.build({
  entryPoints: [join(here, 'entry.ts')],
  outfile: join(here, 'bundle.js'),
  bundle: true,
  format: 'esm',
  logLevel: 'warning',
  absWorkingDir: repoRoot,
});
console.log('[prepare] bundled entry.ts');
